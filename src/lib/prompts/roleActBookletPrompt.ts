import type { LlmMessage } from "@/src/lib/llm/llmTypes";

export function buildRoleActBookletPrompt(input: {
  roleName: string;
  actIndex: number;
  sourceText: string;
}): LlmMessage[] {
  return [
    {
      role: "system",
      content: [
        "你正在解析一个故事分享型情感剧本杀的角色本。",
        "只根据用户提供的当前角色当前幕文本抽取信息。",
        "不要编造未出现的信息，不要推测后续幕，不要使用其他角色视角或 DM 信息。",
        "",
        "【人物指代处理规则】",
        "剧本文本中可能大量出现“他”“她”“那个人”“那个男人”“那个女人”“一位男性”“一个女孩”“一个孩子”等模糊指代。你必须谨慎处理这些指代。",
        "1. 只有当当前文本中有充分上下文证据时，才可以把模糊指代确定为某个具体人物或角色名。",
        "充分证据包括：原文直接写出姓名、称呼或身份；前后文明确说明这个人和某个已知人物是同一个人；这个人的独特事件、关系、身份、行为与前文某人唯一匹配；同一段连续叙事中已经明确建立了该指代对象。",
        "2. 以下情况不能作为确定依据：只是性别相同；只是前文出现过一个有名字的男人/女人；只是角色数量少所以猜测应该是某人；只是剧情上看起来合理；只是为了让输出更清晰而补全人物名。",
        "3. 如果无法确定是谁，必须保留模糊表达，例如“一个男人”“一位男性”“那个女人”“那个人”“某个孩子”“她”“他”。",
        "4. 如果有一定倾向但证据不足，必须使用不确定表达，例如“可能是 xxx 的男人”“疑似 xxx”“似乎与 xxx 有关”“可能指向前文提到的 xxx，但原文没有明确说明”。",
        "5. 不允许把不确定指代写成确定事实。原文只写“一位男性”，前文出现过“陈某”但没有明确证据时，不能输出“陈某来找过我”，应输出“一位男性来找过我”。",
        "6. mustShare / mayShare / relationshipPoints / timelineFragments 中同样遵守该规则。不确定的人物关系不能写成确定关系；不确定的事件参与者不能写成确定角色名。",
        "7. privateText 的整理也不能强行替换代词。如果原文刻意模糊，应保留模糊性。",
        "【分享字段定义】",
        "mustShare：当前幕分享阶段合理应该公开、且对全桌推进有帮助的信息。优先包括公共探索事实、共同经历、关键发现、明显需要同步给其他玩家的事实。",
        "不要把所有重要私密记忆都放进 mustShare。不要把角色独有的创伤、可能自证不利的秘密、尚不确定是否该说的记忆，默认放进 mustShare。除非原文明确要求必须公开，或该信息明显是当前分享环节必须同步的核心事实。",
        "mayShare：可以公开但不强制的信息。包括私密记忆、情绪、创伤、关系感受、对某人的怀疑、尚未确定是否对自己不利的内容。",
        "mustNotShare：只有原文明确说不能说、是秘密、不要告诉别人、暂时不能公开时才填写。允许为空。",
        "华丽文风可以整理为清晰表达，但不要丢失情绪、关系张力和事实边界；人物指代保守原则优先级高于整理为清晰表达。"
      ].join("\n")
    },
    {
      role: "user",
      content: [
        `roleName: ${input.roleName}`,
        `actIndex: ${input.actIndex}`,
        "",
        "请输出结构化 JSON，字段必须符合 schema：",
        "- roleName 必须等于输入 roleName。",
        "- actIndex 必须等于输入 actIndex。",
        "- privateText 不应为空，应整理为当前幕私密读本摘要，不要逐字复写整段原文。目标长度通常控制在 1200 字以内；原文特别长时优先保留关键事实、情绪、关系和时间线。必须忠于原文。整理 privateText 时可以让语言更清楚，但不得把原文模糊的人物指代强行改成具体角色名。如果原文只写“一个男人 / 那个人 / 她”，且上下文不足以确定是谁，privateText 中也应保留这种模糊性。",
        "- mustShare 尽量不为空；如果当前幕确实没有可分享信息，可以为空并写 warning。mustShare 是当前幕分享阶段合理应该公开、且对全桌推进有帮助的信息，优先放公共探索事实、共同经历、关键发现、明显需要同步给其他玩家的事实。不要把所有重要私密记忆、角色独有创伤、可能自证不利的秘密、尚不确定是否该说的记忆默认放进 mustShare，除非原文明确要求必须公开，或该信息明显是当前分享环节必须同步的核心事实。mustShare 不能把不确定人物指代说成确定事实。如果原文只写“一个男人”，mustShare 中也应写“一个男人”；只有证据充分时才写具体姓名。有倾向但不确定时，用“可能是 / 疑似 / 似乎是”。",
        "- mayShare 是可以公开但不强制的信息。可以包含私密记忆、情绪、创伤、关系感受、对某人的怀疑、尚未确定是否对自己不利的内容，也可以包含推测性表达，但必须标明不确定性。不要把“可能是某人”写成“就是某人”。",
        "- mustShare / mayShare / emotionalPoints / relationshipPoints / timelineFragments 每项都应是简洁要点，不要复制大段原文。",
        "- mustNotShare 可以为空；不要为了填字段而脑补禁止项。",
        "- relationshipPoints 中的人物关系必须区分“明确关系”和“疑似关系”。如果关系对象不确定，保留“某个男人 / 那个人”等表达，或写“可能与 xxx 有关”，不要写成确定关系。",
        "- timelineFragments 中的事件参与者如果不确定，保留原文模糊称呼。不要因为前文出现过同性别人物就替换为该人物。",
        "- warnings 中记录人物指代不确定问题，例如“原文中的‘一位男性’证据不足，因此未确定为具体角色。”",
        "",
        "输出前请自检：",
        "1. 我是否把“一个男人 / 一个女人 / 那个人 / 他 / 她”等模糊称呼替换成了具体姓名？",
        "2. 如果替换了，当前文本是否有充分证据？",
        "3. 如果证据不足，请改回模糊称呼，或使用“可能是 xxx / 疑似 xxx”的表达。",
        "4. 不要为了让故事更顺而补全身份。",
        "",
        "当前角色当前幕文本如下：",
        input.sourceText
      ].join("\n")
    }
  ];
}
